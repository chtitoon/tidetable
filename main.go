package main

import (
	"context"
	"fmt"
	"log"
	"strings"
	"time"

	"github.com/chtitoon/tidetable/config"
	"github.com/chtitoon/tidetable/tidal"
	"github.com/chtitoon/tidetable/venues"
)

func main() {
	ctx := context.Background()

	// Load configuration
	cfg, err := config.Load()
	if err != nil {
		log.Fatalf("Failed to load configuration: %v", err)
	}

	fmt.Printf("Loading venues from: %s\n", cfg.VenuesFile)

	// Load venues
	venueList, err := venues.LoadVenues(cfg.VenuesFile)
	if err != nil {
		log.Fatalf("Failed to load venues: %v", err)
	}

	fmt.Printf("Loaded %d venue(s)\n\n", len(venueList))

	// Calculate date range
	now := time.Now()
	endDate := now.AddDate(0, 0, cfg.DaysAhead)

	fmt.Printf("Scraping venues for shows from %s to %s (%d days)...\n",
		now.Format("Jan 2"), endDate.Format("Jan 2, 2006"), cfg.DaysAhead)

	// Scrape all venues for shows in the configured time window
	shows, err := venues.ScrapeAllVenues(venueList, cfg.DaysAhead)
	if err != nil {
		log.Fatalf("Failed to scrape venues: %v", err)
	}

	fmt.Printf("\n=== Found %d show(s) in the next %d days ===\n\n", len(shows), cfg.DaysAhead)

	if len(shows) == 0 {
		fmt.Println("No shows found for this week. Try again later!")
		return
	}

	// Print shows
	for _, show := range shows {
		fmt.Printf("📅 %s - %s at %s\n", show.Date.Format("Mon Jan 2"), show.Artist, show.Venue)
		if show.Price != "" {
			fmt.Printf("   💵 %s\n", show.Price)
		}
		fmt.Printf("   🔗 %s\n\n", show.URL)
	}

	// Initialize Tidal client
	fmt.Println("Connecting to Tidal...")
	tidalClient := tidal.NewClient(cfg.TidalClientID, cfg.TidalClientSecret, "")
	tidalClient.SetTokens(cfg.TidalAccessToken, cfg.TidalRefreshToken)

	// Deduplicate artists (venues may list the same show multiple times)
	uniqueArtists := make(map[string]bool)
	var artistsToSearch []string
	for _, show := range shows {
		if !uniqueArtists[show.Artist] {
			uniqueArtists[show.Artist] = true
			artistsToSearch = append(artistsToSearch, show.Artist)
		}
	}

	fmt.Printf("\nFound %d unique artists from %d shows\n", len(artistsToSearch), len(shows))

	// Search for each artist on Tidal and collect track IDs
	fmt.Println("Searching for artists on Tidal...")
	var trackIDs []string

	for i, artist := range artistsToSearch {
		// Add delay between requests to avoid rate limiting (except for first request)
		// Tidal API has strict rate limits, so we need to be conservative
		if i > 0 {
			time.Sleep(500 * time.Millisecond)
		}

		fmt.Printf("  Searching for %s...", artist)

		artistID, err := tidalClient.SearchArtist(ctx, artist)
		if err != nil {
			fmt.Printf(" not found\n")
			continue
		}

		// Delay between search and getting tracks to avoid rate limiting
		time.Sleep(300 * time.Millisecond)

		// Get top track for this artist (just 1 song)
		tracks, err := tidalClient.GetArtistTopTracks(ctx, artistID, 1) // Get just 1 track
		if err != nil {
			fmt.Printf(" found but no tracks\n")
			continue
		}

		trackIDs = append(trackIDs, tracks...)
		fmt.Printf(" ✓ added %d track(s)\n", len(tracks))
	}

	if len(trackIDs) == 0 {
		fmt.Println("\nNo tracks found on Tidal. Cannot create playlist.")
		return
	}

	fmt.Printf("\n=== Creating playlist with %d tracks ===\n", len(trackIDs))

	// Generate dynamic playlist name with date range
	startDate := now.Format("Jan 2")
	endDateFormatted := endDate.Format("Jan 2, 2006")

	var playlistName string
	if cfg.DaysAhead == 7 {
		playlistName = fmt.Sprintf("%s: %s - %s", cfg.PlaylistNameBase, startDate, endDate.Format("Jan 2"))
	} else if cfg.DaysAhead == 30 || cfg.DaysAhead == 31 {
		playlistName = fmt.Sprintf("%s: %s", cfg.PlaylistNameBase, now.Format("January 2006"))
	} else {
		playlistName = fmt.Sprintf("%s: %s - %s", cfg.PlaylistNameBase, startDate, endDate.Format("Jan 2"))
	}

	// Get unique venues
	venueMap := make(map[string]bool)
	for _, show := range shows {
		venueMap[show.Venue] = true
	}
	var venueNames []string
	for venueName := range venueMap {
		venueNames = append(venueNames, venueName)
	}

	description := fmt.Sprintf("Shows from %s to %s\n\nVenues: %s\n\n🎵 Generated by TideTable",
		startDate, endDateFormatted, strings.Join(venueNames, ", "))

	// Create or update playlist
	playlistID, err := tidalClient.CreateOrUpdatePlaylist(ctx, playlistName, description, trackIDs)
	if err != nil {
		log.Fatalf("Failed to create playlist: %v", err)
	}

	fmt.Printf("\n✅ Playlist '%s' created/updated successfully!\n", playlistName)
	fmt.Printf("🎵 Playlist ID: %s\n", playlistID)
	fmt.Printf("🔗 https://listen.tidal.com/playlist/%s\n", playlistID)
}
